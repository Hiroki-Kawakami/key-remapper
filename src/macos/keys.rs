const MODIFIER_MASKS: &[(u16, u64)] = &[
    (0x3B, 0x0000_0001),
    (0x38, 0x0000_0002),
    (0x3C, 0x0000_0004),
    (0x37, 0x0000_0008),
    (0x36, 0x0000_0010),
    (0x3A, 0x0000_0020),
    (0x3D, 0x0000_0040),
    (0x3E, 0x0000_2000),
    (0x3F, 0x0080_0000),
];

pub fn modifier_mask(keycode: u16) -> Option<u64> {
    MODIFIER_MASKS
        .iter()
        .find(|(k, _)| *k == keycode)
        .map(|(_, m)| *m)
}
